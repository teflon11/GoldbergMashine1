  function makeTopSeg(Matter) {
    return function topSeg(x1, y1, x2, y2, th, opts) {
      var dx = x2 - x1, dy = y2 - y1;
      var len = Math.sqrt(dx * dx + dy * dy);
      var ang = Math.atan2(dy, dx);
      var nx = -Math.sin(ang), ny = -Math.cos(ang);
      var o = { isStatic: true, friction: 0.04, restitution: 0.05, angle: ang };
      for (var k in (opts || {})) o[k] = opts[k];
      var body = Matter.Bodies.rectangle(
        (x1 + x2) / 2 - nx * th / 2, (y1 + y2) / 2 - ny * th / 2, len, th, o);
      body.__top = [[x1, y1], [x2, y2]];
      return body;
    };
  }

